-- 1. USERS TABLE
CREATE TABLE USERS (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR2(150) NOT NULL,
    email VARCHAR2(255) NOT NULL UNIQUE,
    password_hash VARCHAR2(255) NOT NULL,
    role VARCHAR2(20) DEFAULT 'user' NOT NULL,
    languages_known VARCHAR2(255),
    area_of_interest VARCHAR2(255),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT chk_user_role CHECK (role IN ('user', 'admin'))
);

-- 2. RESUME TABLE
CREATE TABLE RESUME (
    resume_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    filename VARCHAR2(255) NOT NULL,
    file_path VARCHAR2(500) NOT NULL,
    file_type VARCHAR2(10) NOT NULL,
    version_number NUMBER DEFAULT 1 NOT NULL,
    raw_text CLOB,
    is_active NUMBER(1) DEFAULT 1 NOT NULL,
    uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_resume_user FOREIGN KEY (user_id) REFERENCES USERS(user_id) ON DELETE CASCADE,
    CONSTRAINT chk_resume_file_type CHECK (file_type IN ('pdf', 'docx'))
);

-- 3. RESUME_ANALYSIS TABLE
CREATE TABLE RESUME_ANALYSIS (
    analysis_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resume_id NUMBER NOT NULL,
    user_id NUMBER NOT NULL,
    extracted_json CLOB NOT NULL,
    total_score NUMBER(5,2) DEFAULT 0 NOT NULL,
    completeness_score NUMBER(5,2) DEFAULT 0 NOT NULL,
    skills_score NUMBER(5,2) DEFAULT 0 NOT NULL,
    projects_score NUMBER(5,2) DEFAULT 0 NOT NULL,
    verbs_score NUMBER(5,2) DEFAULT 0 NOT NULL,
    readability_score NUMBER(5,2) DEFAULT 0 NOT NULL,
    predicted_category VARCHAR2(150),
    confidence_score NUMBER(5,4) DEFAULT 0,
    feedback_json CLOB,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_analysis_resume FOREIGN KEY (resume_id) REFERENCES RESUME(resume_id) ON DELETE CASCADE,
    CONSTRAINT fk_analysis_user FOREIGN KEY (user_id) REFERENCES USERS(user_id) ON DELETE CASCADE
);

-- 4. ADMIN_REVIEW TABLE
CREATE TABLE ADMIN_REVIEW (
    review_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_id NUMBER NOT NULL,
    resume_id NUMBER NOT NULL,
    user_id NUMBER NOT NULL,
    admin_id NUMBER,
    review_status VARCHAR2(30) DEFAULT 'Pending Review' NOT NULL,
    admin_comments CLOB,
    verified_category VARCHAR2(150),
    corrected_data_json CLOB,
    reviewed_at TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_review_analysis FOREIGN KEY (analysis_id) REFERENCES RESUME_ANALYSIS(analysis_id) ON DELETE CASCADE,
    CONSTRAINT fk_review_resume FOREIGN KEY (resume_id) REFERENCES RESUME(resume_id) ON DELETE CASCADE,
    CONSTRAINT fk_review_user FOREIGN KEY (user_id) REFERENCES USERS(user_id) ON DELETE CASCADE,
    CONSTRAINT fk_review_admin FOREIGN KEY (admin_id) REFERENCES USERS(user_id) ON DELETE SET NULL,
    CONSTRAINT chk_review_status CHECK (review_status IN ('Pending Review', 'Approved', 'Improvement Required'))
);

-- 5. SKILL_CATEGORY TABLE
CREATE TABLE SKILL_CATEGORY (
    category_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR2(150) NOT NULL UNIQUE,
    description VARCHAR2(500),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 6. SKILL TABLE
CREATE TABLE SKILL (
    skill_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id NUMBER NOT NULL,
    skill_name VARCHAR2(100) NOT NULL UNIQUE,
    aliases VARCHAR2(255),
    CONSTRAINT fk_skill_category FOREIGN KEY (category_id) REFERENCES SKILL_CATEGORY(category_id) ON DELETE CASCADE
);

-- 7. USER_SKILL TABLE
CREATE TABLE USER_SKILL (
    user_skill_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    resume_id NUMBER NOT NULL,
    skill_name VARCHAR2(100) NOT NULL,
    category_name VARCHAR2(150),
    detected_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_userskill_user FOREIGN KEY (user_id) REFERENCES USERS(user_id) ON DELETE CASCADE,
    CONSTRAINT fk_userskill_resume FOREIGN KEY (resume_id) REFERENCES RESUME(resume_id) ON DELETE CASCADE
);

-- 8. RESUME_SUGGESTION TABLE
CREATE TABLE RESUME_SUGGESTION (
    suggestion_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resume_id NUMBER NOT NULL,
    original_text CLOB NOT NULL,
    suggested_text CLOB NOT NULL,
    action_verb VARCHAR2(50),
    explanation VARCHAR2(500),
    status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    user_final_text CLOB,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_sugg_resume FOREIGN KEY (resume_id) REFERENCES RESUME(resume_id) ON DELETE CASCADE,
    CONSTRAINT chk_sugg_status CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'EDITED'))
);

-- 9. QUESTION_BANK TABLE
CREATE TABLE QUESTION_BANK (
    question_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id NUMBER,
    topic VARCHAR2(100) NOT NULL,
    question_type VARCHAR2(20) DEFAULT 'MCQ' NOT NULL,
    difficulty VARCHAR2(20) DEFAULT 'Intermediate' NOT NULL,
    question_text CLOB NOT NULL,
    option_a VARCHAR2(500),
    option_b VARCHAR2(500),
    option_c VARCHAR2(500),
    option_d VARCHAR2(500),
    correct_answer VARCHAR2(500) NOT NULL,
    explanation CLOB,
    rubric_keywords VARCHAR2(500),
    aptitude_section VARCHAR2(50),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_qbank_category FOREIGN KEY (category_id) REFERENCES SKILL_CATEGORY(category_id) ON DELETE SET NULL,
    CONSTRAINT chk_qbank_type CHECK (question_type IN ('MCQ', 'DESCRIPTIVE', 'APTITUDE')),
    CONSTRAINT chk_qbank_diff CHECK (difficulty IN ('Beginner', 'Intermediate', 'Advanced'))
);

-- 10. MOCK_INTERVIEW TABLE
CREATE TABLE MOCK_INTERVIEW (
    interview_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    category_id NUMBER,
    difficulty VARCHAR2(20) DEFAULT 'Intermediate' NOT NULL,
    total_questions NUMBER DEFAULT 5 NOT NULL,
    score_percentage NUMBER(5,2) DEFAULT 0 NOT NULL,
    status VARCHAR2(20) DEFAULT 'COMPLETED' NOT NULL,
    completed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_interview_user FOREIGN KEY (user_id) REFERENCES USERS(user_id) ON DELETE CASCADE,
    CONSTRAINT fk_interview_cat FOREIGN KEY (category_id) REFERENCES SKILL_CATEGORY(category_id) ON DELETE SET NULL
);

-- 11. INTERVIEW_RESPONSE TABLE
CREATE TABLE INTERVIEW_RESPONSE (
    response_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    interview_id NUMBER NOT NULL,
    question_id NUMBER NOT NULL,
    user_answer CLOB,
    is_correct NUMBER(1) DEFAULT 0,
    points_earned NUMBER(5,2) DEFAULT 0,
    feedback CLOB,
    CONSTRAINT fk_resp_interview FOREIGN KEY (interview_id) REFERENCES MOCK_INTERVIEW(interview_id) ON DELETE CASCADE,
    CONSTRAINT fk_resp_question FOREIGN KEY (question_id) REFERENCES QUESTION_BANK(question_id) ON DELETE CASCADE
);

-- 12. APTITUDE_ATTEMPT TABLE
CREATE TABLE APTITUDE_ATTEMPT (
    attempt_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    total_questions NUMBER DEFAULT 15 NOT NULL,
    correct_count NUMBER DEFAULT 0 NOT NULL,
    score_percentage NUMBER(5,2) DEFAULT 0 NOT NULL,
    quant_score NUMBER(5,2) DEFAULT 0 NOT NULL,
    logical_score NUMBER(5,2) DEFAULT 0 NOT NULL,
    verbal_score NUMBER(5,2) DEFAULT 0 NOT NULL,
    started_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    completed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_aptitude_user FOREIGN KEY (user_id) REFERENCES USERS(user_id) ON DELETE CASCADE
);

-- 13. APTITUDE_RESPONSE TABLE
CREATE TABLE APTITUDE_RESPONSE (
    resp_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id NUMBER NOT NULL,
    question_id NUMBER NOT NULL,
    selected_option VARCHAR2(10),
    is_correct NUMBER(1) DEFAULT 0 NOT NULL,
    points NUMBER(3,1) DEFAULT 0 NOT NULL,
    CONSTRAINT fk_aptresp_attempt FOREIGN KEY (attempt_id) REFERENCES APTITUDE_ATTEMPT(attempt_id) ON DELETE CASCADE,
    CONSTRAINT fk_aptresp_question FOREIGN KEY (question_id) REFERENCES QUESTION_BANK(question_id) ON DELETE CASCADE
);

-- 14. LEARNING_RESOURCE TABLE
CREATE TABLE LEARNING_RESOURCE (
    resource_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id NUMBER,
    topic VARCHAR2(100) NOT NULL,
    title VARCHAR2(255) NOT NULL,
    resource_url VARCHAR2(500) NOT NULL,
    resource_type VARCHAR2(50) DEFAULT 'Tutorial' NOT NULL,
    description VARCHAR2(500),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_resource_cat FOREIGN KEY (category_id) REFERENCES SKILL_CATEGORY(category_id) ON DELETE SET NULL
);

-- Create performance indexes
CREATE INDEX idx_resume_user ON RESUME(user_id);
CREATE INDEX idx_analysis_user ON RESUME_ANALYSIS(user_id);
CREATE INDEX idx_admin_review_status ON ADMIN_REVIEW(review_status);
CREATE INDEX idx_qbank_category ON QUESTION_BANK(category_id, difficulty);
CREATE INDEX idx_userskill_user ON USER_SKILL(user_id);
